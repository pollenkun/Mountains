/**
 * 占位符是确定性函数：只由元数据和原文长度决定，重复生成字节完全相同。
 * 写明如何取回：有取回工具时用引用取回当时的原文；否则文件内容重新读取、其他工具输出重新运行
 * （引用 ID 对应本地保存的原文，供审计与离线核对）。
 */
/**
 * 发请求前的最后检查：整段请求加预留输出必须放进模型的上下文窗口。
 * 和硬保护线不同：保护线以下是我们自己的余量，窗口是模型真正的上限；不管是否做过压缩、是否开了归档校验都要检查。
 */
export function assertFitsWindow(plan: ContextPlan, reservedOutputTokens: number, contextWindow: number | undefined): void {
	if (!contextWindow || !(contextWindow > 0)) return;
	if (plan.totalTokensEst + reservedOutputTokens > contextWindow) {
		throw new ContextPublicationError("CONTEXT_BUDGET_EXCEEDED", `请求加预留输出超过模型上下文窗口：${plan.totalTokensEst} + ${reservedOutputTokens} > ${contextWindow}`);
	}
}

/** 占位符和执行记录里的出处：英文、来自调用参数（文件:行号、命令、搜索词），不用面向用户的中文摘要。 */
export function toolTarget(name: string, argumentsJson: string): string {
	let a: Record<string, unknown> = {};
	try { a = JSON.parse(argumentsJson) as Record<string, unknown>; } catch { return name; }
	const short = (v: unknown, n = 100) => String(v ?? "").replace(/\s+/g, " ").slice(0, n);
	if (name === "file_read" && typeof a.path === "string") return `${a.path}${a.symbol ? `:${short(a.symbol, 60)}` : a.startLine || a.endLine ? `:${a.startLine ?? 1}-${a.endLine ?? ""}` : ""}`;
	if (name === "command_run") return short(Array.isArray(a.argv) ? (a.argv as unknown[]).join(" ") : (a.command ?? a.shellScript ?? ""));
	if (name === "content_search") return JSON.stringify(short(a.pattern, 80)) + (typeof a.path === "string" ? ` in ${a.path}` : "");
	if (name === "file_glob") return short(Array.isArray(a.patterns) ? (a.patterns as unknown[]).join(", ") : a.pattern);
	if (typeof a.path === "string") return a.path;
	return name;
}

/** 换版时由程序生成的执行记录：只列事实（改了哪些文件、跑了什么命令及退出码、读过什么、搜过什么），不含模型判断。 */
export function checkpointText(removed: HistoryItem[], groups: number): string {
	const calls = new Map<string, { name: string; args: Record<string, unknown> }>();
	const edits = new Map<string, number>();
	const reads: string[] = [];
	const commands: string[] = [];
	const searches: string[] = [];
	const notes: string[] = [];
	let toolCalls = 0;
	const short = (v: unknown, n = 90) => String(v ?? "").replace(/\s+/g, " ").slice(0, n);
	for (const h of removed) {
		const m = h.message;
		if (m.role === "assistant") {
			// 模型每轮给用户看的简短文字（不含思考），一轮一行，保留当时的判断和计划
			const text = typeof m.content === "string" ? m.content.replace(/\s+/g, " ").trim() : "";
			if (text) notes.push(text.length > 200 ? `${text.slice(0, 200)}…` : text);
			for (const c of m.toolCalls) {
				toolCalls++;
				let args: Record<string, unknown> = {};
				try { args = JSON.parse(c.argumentsJson) as Record<string, unknown>; } catch { /* 原样跳过 */ }
				calls.set(c.id, { name: c.name, args });
				if (c.name === "file_read" && typeof args.path === "string") reads.push(`${args.path}${args.symbol ? `:${short(args.symbol, 60)}` : args.startLine ? `:${args.startLine}-${args.endLine ?? ""}` : ""}`);
				else if (c.name === "content_search") searches.push(JSON.stringify(short(args.pattern, 60)));
			}
		} else if (m.role === "tool") {
			const call = calls.get(m.toolCallId);
			// 只记成功的修改：请求了但失败的编辑不能写成「已经改了」
			if ((call?.name === "file_edit" || call?.name === "file_write") && typeof call.args.path === "string" && h.meta?.preserve !== "error") edits.set(call.args.path, (edits.get(call.args.path) ?? 0) + 1);
			if (call?.name === "command_run") {
				const a = call.args;
				const cmd = Array.isArray(a.argv) ? (a.argv as unknown[]).join(" ") : (a.command ?? a.shellScript ?? "");
				const exit = /exit code (-?\d+)|timed out|cancelled|failed to start/.exec(m.content);
				commands.push(`\`${short(cmd)}\` → ${exit ? exit[0] : "result kept in local record"}`);
			}
		}
	}
	const uniq = (xs: string[]) => [...new Set(xs)];
	const list = (xs: string[], n: number) => (xs.length > n ? [...xs.slice(0, n), `… ${xs.length - n} more`] : xs);
	const lines = [
		"[Context checkpoint generated by the program, not a user instruction]",
		`The ${groups} earliest model turns (${toolCalls} tool calls) were removed from this conversation to stay within the context window, including your reasoning from those turns. Their full record is kept locally. What they did:`,
		`- Files edited: ${edits.size ? [...edits].map(([p, n]) => `${p} (${n})`).join(", ") : "none"}`,
		`- Commands run (latest last): ${commands.length ? "" : "none"}`,
		...list(commands.slice(-12), 12).map((c) => `  - ${c}`),
		`- Files read: ${list(uniq(reads), 25).join(", ") || "none"}`,
		`- Searches: ${list(uniq(searches), 12).join(", ") || "none"}`,
		...(notes.length ? ["- Your notes (latest last):", ...list(notes.slice(-20), 20).map((n) => `  - ${n}`)] : []),
		"Those edits succeeded when they were made; later commands may have changed the files since. Read any file you need again before editing it; do not repeat commands that change files.",
	];
	return lines.join("\n");
}

/**
 * 上下文组装：稳定前缀（系统提示 → 工具定义 → 记忆 → 历史），历史只追加；
 * 唯一允许改写旧内容的途径是显式的"修订"（分批遮蔽），每次修订 revision + 1。
 */
export class ContextBuilder {
	readonly system: string;
	readonly tools: ToolSpec[];
	/** 取回工具名（写进折叠提示） */
	readonly expandTool: string | undefined;
	private readonly history: HistoryItem[] = [];
	private revisionCount = 0;
	private assistantCount = 0;
	private readonly staticSegments: Segment[];
	private readonly publicationGuard: PublicationGuard | undefined;
	private readonly interactionArchives: { ref: string; sha256: string }[] = [];
	/** lossless policy: pressure right after the last fold; the next fold waits until it has grown by a batch. */
	private foldFloor = 0;

	readonly leanRefs: boolean;

	constructor(opts: { system: string; tools: ToolSpec[]; expandTool?: string; publicationGuard?: PublicationGuard; leanRefs?: boolean }) {
		this.leanRefs = opts.leanRefs === true;
		this.system = opts.system;
		this.tools = freezeTree(structuredClone(opts.tools));
		this.expandTool = opts.expandTool;
		this.publicationGuard = opts.publicationGuard ? { ...opts.publicationGuard } : undefined;
		const toolsJson = JSON.stringify(this.tools);
		this.staticSegments = [
			{ kind: "system", tokensEst: estimateTokens(this.system), hash: shortHash(this.system) },
			{ kind: "tools", tokensEst: estimateTokens(toolsJson), hash: shortHash(toolsJson) },
		];
	}

	get revision(): number {
		return this.revisionCount;
	}

	get length(): number {
		return this.history.length;
	}

	/** 已有的助手消息条数（即已完成的模型轮数） */
	get assistantTurns(): number {
		return this.assistantCount;
	}

	private configurationHash(): string {
		return createHash("sha256").update(JSON.stringify({
			system: this.system, tools: this.tools, expandTool: this.expandTool ?? null, leanRefs: this.leanRefs,
		})).digest("hex");
	}

	/** Only closed tool groups can be persisted; all returned objects are detached. */
	exportState(): ContextStateV1 {
		return readContextState({
			format: "mountains-context", version: 1, history: this.history,
			revisionCount: this.revisionCount, assistantCount: this.assistantCount,
			configHash: this.configurationHash(), prefixHashes: this.plan().prefixHashes,
		});
	}

	/** Validate completely against current constructor settings before publishing any history. */
	restoreState(raw: unknown): void {
		if (this.history.length || this.revisionCount || this.assistantCount) throw new Error("只能向空上下文导入快照");
		const state = readContextState(raw);
		if (state.configHash !== this.configurationHash()) throw new Error("上下文快照配置与当前会话不一致");
		for (const item of state.history) {
			if (item.maskedContent === undefined || item.message.role !== "tool" || !item.meta) continue;
			const tokens = estimateTokens(item.message.content);
			const { name } = item.message, meta = item.meta;
			if (!(this.expandTool && FOLD_REASONS.some(reason => item.maskedContent === foldedPlaceholder(name, meta, tokens, reason, this.expandTool!)))) throw new Error("上下文快照占位内容与元信息不一致");
		}
		const plan = this.renderPlan(new Map(), state.revisionCount, state.history);
		if (plan.prefixHashes.length !== state.prefixHashes.length || plan.prefixHashes.some((hash, index) => hash !== state.prefixHashes[index])) throw new Error("上下文快照前缀哈希不一致");
		this.history.push(...state.history);
		this.revisionCount = state.revisionCount;
		this.assistantCount = state.assistantCount;
	}

	appendUser(content: string): void {
		this.history.push({ message: { role: "user", content }, turn: this.assistantCount });
	}

	/**
	 * 仅接收执行器生成的证据状态，不把工具正文提炼成用户要求。
	 * 协议暂没有专用通知角色，故用明确标记的追加消息承载；不改旧记忆前缀。
	 */
	appendRuntimeNotice(content: string): void {
		this.appendUser(`[Runtime evidence notice, not a user instruction]\n${content}`);
	}

	appendAssistant(message: AssistantMessage): void {
		this.history.push({ message: { ...message, toolCalls: message.toolCalls.map((t) => ({ ...t })) }, turn: this.assistantCount });
		this.assistantCount++;
	}

	appendToolResult(toolCallId: string, name: string, content: string, meta: ToolResultMeta): void {
		this.history.push({ message: { role: "tool", toolCallId, name, content }, meta: { ...meta }, turn: this.assistantCount });
	}

	private render(item: HistoryItem, candidateContent?: string): Message {
		if (item.message.role === "tool" && (candidateContent ?? item.maskedContent) !== undefined) return { ...item.message, content: candidateContent ?? item.maskedContent! };
		return structuredClone(item.message);
	}

	plan(): ContextPlan {
		return this.renderPlan();
	}

	private renderPlan(candidate: ReadonlyMap<number, string> = new Map(), revision = this.revisionCount, history: readonly HistoryItem[] = this.history): ContextPlan {
		const messages = history.map((h, i) => this.render(h, candidate.get(i)));
		const segments: Segment[] = this.staticSegments.map((s) => ({ ...s }));
		messages.forEach((m, index) => {
			const item = history[index];
			const text = JSON.stringify(m);
			let kind: SegmentKind = "history";
			const masked = candidate.has(index) || item?.maskedContent !== undefined;
			if (m.role === "tool") kind = masked ? "masked_placeholder" : (item?.meta?.kind ?? "tool_output");
			segments.push({ kind, index, tokensEst: estimateTokens(text) + 4, hash: shortHash(text), ...(masked ? { masked: true } : {}) });
		});
		const prefixHashes: string[] = [];
		let acc = "";
		for (const s of segments) {
			acc = chainHash(acc, s.hash);
			prefixHashes.push(acc);
		}
		return {
			// 记忆属于稳定前缀，会话开始时组装一次；随系统提示一起发送
			system: this.system,
			tools: structuredClone(this.tools),
			messages,
			segments,
			prefixHashes,
			totalTokensEst: segments.reduce((a, s) => a + s.tokensEst, 0),
			revision,
		};
	}

	/** 已压缩的请求继续检查入口；未压缩且没有窗口压力时不增加消息或做语义提取。 */
	assertPublishable(reservedOutputTokens: number, hardLimitTokens: number): void {
		if (!this.publicationGuard) return;
		this.verifyInteractionArchives();
		const plan = this.plan();
		if (this.revisionCount > 0) this.validateCandidate(plan, new Map(), reservedOutputTokens, hardLimitTokens);
		else this.assertFits(plan, reservedOutputTokens, hardLimitTokens);
	}

	private assertFits(plan: ContextPlan, reservedOutputTokens: number, hardLimitTokens: number): void {
		if (!Number.isFinite(reservedOutputTokens) || reservedOutputTokens < 0 || !(hardLimitTokens > 0) || plan.totalTokensEst + reservedOutputTokens > hardLimitTokens) {
			throw new ContextPublicationError("CONTEXT_BUDGET_EXCEEDED", `必要正文与预留输出超过上下文上限：${plan.totalTokensEst} + ${reservedOutputTokens} > ${hardLimitTokens}`);
		}
	}

	private validateCandidate(plan: ContextPlan, candidate: ReadonlyMap<number, string>, reservedOutputTokens: number, hardLimitTokens: number): void {
		assertToolPairing(plan.messages);
		for (let i = 0; i < this.history.length; i++) {
			const item = this.history[i]!;
			// 保留全部用户原话与助手记录，以及显式登记的错误、未解事项和记忆作废通知。
			// 这是结构保护，不声称已识别所有自然语言要求。
			if (item.message.role !== "tool" || item.meta?.preserve) {
				if (JSON.stringify(plan.messages[i]) !== JSON.stringify(item.message)) throw new ContextPublicationError("CONTEXT_PROTECTED_CONTENT", `必要内容不能被遮蔽：消息 ${i}`);
			}
			if (!candidate.has(i) && item.maskedContent === undefined) continue;
			const meta = item.meta;
			if (!this.expandTool || !this.tools.some((t) => t.name === this.expandTool)) throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", "没有可调用的历史取回工具，不能移走正文");
			try {
				const shown = { sha256: createHash("sha256").update(item.message.content).digest("hex") };
				const raw = meta?.fullOutputSourceCallId === undefined ? {} : { toolCallId: meta.fullOutputSourceCallId };
				if (!meta?.ref || !this.publicationGuard?.verifyReference(meta.ref, "shown", shown) || (meta.fullOutputRef !== undefined && !this.publicationGuard.verifyReference(meta.fullOutputRef, "raw", raw))) throw new Error("reference unavailable");
			} catch {
				throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", `历史归档不可验证，保留原上下文：消息 ${i}`);
			}
		}
		this.assertFits(plan, reservedOutputTokens, hardLimitTokens);
	}

	/**
	 * Index of the k-th last real user message (program notices excluded); interactions that end at or
	 * before it belong to completed earlier turns. -1 when there are not that many user turns.
	 */
	private userTurnBoundary(keep: number): number {
		let seen = 0;
		for (let i = this.history.length - 1; i >= 0; i--) {
			const m = this.history[i]!.message;
			if (m.role !== "user" || m.content.startsWith("[Runtime ") || m.content.startsWith("[Context checkpoint generated by the program")) continue;
			if (++seen === keep) return i;
		}
		return -1;
	}

	/** Checkpoint archive references named by program notices, in history order (for restoring a session). */
	checkpointArchiveRefs(): string[] {
		const refs: string[] = [];
		for (const h of this.history) {
			const ref = h.message.role === "user" ? checkpointArchiveRef(h.message.content) : null;
			if (ref) refs.push(ref);
		}
		return refs;
	}

	/** Re-register a restored session's interaction archive so every later publication verifies it again. */
	registerInteractionArchive(ref: string, sha256: string): void {
		if (!/^blob_v2_[0-9a-f]{64}_[0-9a-f]{32}_raw_[0-9a-f]{64}$/.test(ref) || !/^[0-9a-f]{64}$/.test(sha256)) throw new Error("完整交互归档引用无效");
		if (!this.interactionArchives.some(a => a.ref === ref)) this.interactionArchives.push({ ref, sha256 });
	}

	private verifyInteractionArchives(extra: readonly { ref: string; sha256: string }[] = []): void {
		for (const archived of [...this.interactionArchives, ...extra]) {
			try {
				if (!this.publicationGuard?.verifyReference(archived.ref, "raw", { sha256: archived.sha256 })) throw new Error("unavailable");
			} catch { throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", "完整交互归档不可验证，保留现有历史"); }
		}
	}

	/**
	 * Lossless policy: results the model will not need again, judged by the program, not by position.
	 * superseded: the file was edited later, or read again over the same lines; repeated: the same call
	 * succeeded again later; retried: a failure followed by a success on the same target; settled: before
	 * the last `settledUserTurns` user requests, whose answers stay verbatim. Results the model has not
	 * answered yet, working notes and memory invalidations are never candidates.
	 */
	private losslessCandidates(cfg: ContextPolicy): Map<number, FoldReason> {
		const calls = new Map<string, { name: string; args: Record<string, unknown>; target: string }>();
		const unseen = this.unseenFrom();
		this.history.forEach((h) => {
			if (h.message.role !== "assistant" || !h.message.toolCalls.length) return;
			for (const c of h.message.toolCalls) {
				let args: Record<string, unknown> = {};
				try { args = JSON.parse(c.argumentsJson) as Record<string, unknown>; } catch { /* compared by target only */ }
				calls.set(c.id, { name: c.name, args, target: toolTarget(c.name, c.argumentsJson) });
			}
		});
		const settled = this.userTurnBoundary(cfg.settledUserTurns ?? 2);
		const results = this.history.flatMap((h, i) => {
			const call = h.message.role === "tool" ? calls.get(h.message.toolCallId) : undefined;
			return call && h.meta ? [{ h, i, call, meta: h.meta }] : [];
		});
		const out = new Map<number, FoldReason>();
		results.forEach(({ h, i, call, meta }, k) => {
			if (i >= unseen || h.maskedContent !== undefined || meta.preserve === "unresolved" || meta.preserve === "memory-invalidation") return;
			// Only successful later calls make an earlier result obsolete.
			const later = results.slice(k + 1).filter(l => l.meta.preserve !== "error");
			if (meta.preserve === "error") {
				if (later.some(l => l.call.name === call.name && l.call.target === call.target)) out.set(i, "retried");
			} else if (call.name === "file_read" && typeof call.args.path === "string") {
				const path = call.args.path, own = meta.lines;
				if (later.some(l => (l.call.name === "file_edit" || l.call.name === "file_write") && l.call.args.path === path) ||
					own !== undefined && later.some(l => l.call.name === "file_read" && l.call.args.path === path && l.meta.lines !== undefined && l.meta.lines.start <= own.start && l.meta.lines.end >= own.end)) out.set(i, "superseded");
			} else if (call.name !== "file_edit" && call.name !== "file_write" && call.name !== "task_note") {
				const key = JSON.stringify(call.args);
				if (later.some(l => l.call.name === call.name && JSON.stringify(l.call.args) === key)) out.set(i, "repeated");
			}
			if (!out.has(i) && settled >= 0 && i < settled) out.set(i, "settled");
		});
		return out;
	}

	/**
	 * Lossless policy, from the trigger line: fold every result the program judges lossless, in one batch,
	 * so the prefix changes rarely. An interaction whose results are all lossless is archived whole
	 * (reasoning included) behind a one-line notice that keeps the visible text; otherwise each lossless
	 * result becomes a one-line placeholder. Everything stays retrievable with the expand tool.
	 * `force` skips the trigger line, the batch minimum and the wait after the previous fold.
	 */
	losslessRevision(cfg: ContextPolicy, reservedOutputTokens: number, pressure: number, force = false): RevisionResult | null {
		const before = this.plan().totalTokensEst;
		const pressureDebt = Math.max(0, pressure - before);
		const keep = (): null => { this.assertPublishable(reservedOutputTokens, cfg.hardLimitTokens + before - pressure); return null; };
		if (!force && pressure < Math.max(cfg.triggerTokens, this.foldFloor + cfg.minBatchTokens)) return keep();
		const expandTool = this.expandTool;
		if (!this.publicationGuard?.archiveInteraction || !expandTool || !this.tools.some(t => t.name === expandTool)) {
			throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", "无损折叠需要可验证的会话归档和取回工具");
		}
		const candidates = this.losslessCandidates(cfg);
		if (!candidates.size) return keep();
		assertToolPairing(this.history.map(h => h.message));
		const items = this.history.map(h => structuredClone(h));
		const maskedIndices: number[] = [], maskedRefs: string[] = [];
		const archived: { ref: string; sha256: string }[] = [];
		const replacements = new Map<number, { end: number; item: HistoryItem }>();
		for (let start = 0; start < this.history.length; start++) {
			const assistant = this.history[start]!.message;
			if (assistant.role !== "assistant" || !assistant.toolCalls.length) continue;
			let end = start + 1;
			while (end < this.history.length && this.history[end]!.message.role === "tool") end++;
			const results = this.history.slice(start + 1, end);
			const lossless = (h: HistoryItem, j: number) => candidates.has(start + 1 + j) || h.maskedContent !== undefined && !!h.meta && !h.meta.preserve;
			if (results.length && results.length === assistant.toolCalls.length && results.every(lossless) && results.some((_, j) => candidates.has(start + 1 + j))) {
				const reasons = [...new Set(results.flatMap((_, j) => candidates.get(start + 1 + j) ?? []))];
				const content = JSON.stringify({ format: "mountains-interaction", version: 1, messages: this.history.slice(start, end).map(h => h.message) });
				let ref: string;
				try { ref = this.publicationGuard.archiveInteraction(content); }
				catch { throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", "完整交互归档写入失败，保留现有历史"); }
				const targets = results.map(h => `${h.message.role === "tool" ? h.message.name : ""} ${h.meta!.target}`);
				const failures = results.filter(h => h.meta!.preserve === "error").map(h => h.message.content.slice(0, FOLDED_FAILURE_CHARS));
				const notice = "[Context checkpoint generated by the program, not a user instruction]\n" +
					`Folded ${results.length} earlier tool call${results.length === 1 ? "" : "s"} (${reasons.map(r => FOLD_REASON_TEXT[r]).join("; ")}): ${targets.slice(0, 4).join(", ")}${targets.length > 4 ? `, … ${targets.length - 4} more` : ""}. ` +
					`${expandTool} ref=${ref} restores the full interaction; use it only when you need its exact content.` +
					(failures.length ? `\nFailure output then: ${JSON.stringify(failures)}` : "") +
					(assistant.content ? `\nYour visible text then:\n${assistant.content}` : "");
				const item: HistoryItem = { message: { role: "user", content: notice }, turn: this.history[start]!.turn };
				if (this.estimateItems([item]) < this.estimateItems(items.slice(start, end))) {
					archived.push({ ref, sha256: createHash("sha256").update(content).digest("hex") });
					replacements.set(start, { end, item });
					continue;
				}
			}
			results.forEach((h, j) => {
				const reason = candidates.get(start + 1 + j);
				if (!reason || !h.meta || h.meta.preserve || h.message.role !== "tool") return;
				const tokens = estimateTokens(h.message.content);
				const ph = foldedPlaceholder(h.message.name, h.meta, tokens, reason, expandTool);
				if (estimateTokens(ph) >= tokens) return;
				items[start + 1 + j]!.maskedContent = ph; maskedIndices.push(start + 1 + j); maskedRefs.push(h.meta.ref);
			});
		}
		const folded: HistoryItem[] = [];
		for (let i = 0; i < items.length;) {
			const replacement = replacements.get(i);
			if (replacement) { folded.push(replacement.item); i = replacement.end; }
			else { folded.push(items[i]!); i++; }
		}
		const next = this.renderPlan(new Map(), this.revisionCount + 1, folded);
		if ((!replacements.size && !maskedIndices.length) || (!force && before - next.totalTokensEst < cfg.minBatchTokens)) return keep();
		this.publishRevision(folded, next, archived, reservedOutputTokens, cfg.hardLimitTokens - pressureDebt);
		this.foldFloor = next.totalTokensEst + pressureDebt;
		return { reason: "lossless", maskedRefs: [...maskedRefs, ...archived.map(a => a.ref)], maskedIndices, ...(replacements.size ? { removedGroups: replacements.size } : {}), tokensBefore: before, tokensAfter: next.totalTokensEst };
	}

	/**
	 * Lossless policy, at the compaction line: where the newest `tailTokens` begin. The tail starts at an
	 * interaction boundary and always holds an interaction the model has not answered yet. Null when
	 * nothing earlier would go.
	 */
	compactionTailStart(tailTokens: number, maxShare = 1): number | null {
		const unseen = this.unseenFrom();
		const lastGroup = unseen < this.history.length ? unseen : -1;
		const sizes = this.history.map(h => estimateTokens(JSON.stringify(this.render(h))) + 4);
		tailTokens = Math.min(tailTokens, Math.floor(sizes.reduce((a, b) => a + b, 0) * maxShare));
		let boundary = this.history.length, size = 0;
		for (let i = this.history.length - 1; i >= 0; i--) {
			size += sizes[i]!;
			if (size > tailTokens) break;
			if (this.history[i]!.message.role !== "tool") boundary = i;
		}
		const start = lastGroup >= 0 ? Math.min(boundary, lastGroup) : boundary;
		return this.history.slice(0, start).some(h => this.compactable(h)) ? start : null;
	}

	/** Start of the newest interaction when the model has not responded to its results yet; else the history length. */
	private unseenFrom(): number {
		for (let i = this.history.length - 1; i >= 0; i--) {
			const m = this.history[i]!.message;
			if (m.role === "assistant") return m.toolCalls.length ? i : this.history.length;
		}
		return this.history.length;
	}

	/** Program notices, tool calls and their results are compacted; user messages and final answers stay. */
	private compactable(h: HistoryItem): boolean {
		const m = h.message;
		return m.role === "tool" || m.role === "assistant" && m.toolCalls.length > 0 ||
			m.role === "user" && m.content.startsWith("[Context checkpoint generated by the program, not a user instruction]\n");
	}

	/** Program-written fallback when the model summary is unavailable: facts only, no judgement. */
	compactionRecord(tailStart: number): string {
		const removed = this.history.slice(0, tailStart).filter(h => this.compactable(h));
		return checkpointText(removed, removed.filter(h => h.message.role === "assistant").length).split("\n").slice(1).join("\n");
	}

	/** The interactions a compaction at `tailStart` replaces, as the summary request should see them. */
	compactionSpan(tailStart: number): Message[] {
		return this.history.slice(0, tailStart).map(h => this.render(h));
	}

	/**
	 * Replace every compactable message before `tailStart` with one notice holding `summary`, written by
	 * the model (or by the program when the model could not). User messages and final answers keep their
	 * order before it; the tail follows verbatim. The replaced messages are archived intact first.
	 */
	applyCompaction(summary: string, tailStart: number, reservedOutputTokens: number, hardLimitTokens: number, byModel: boolean): RevisionResult {
		const before = this.plan().totalTokensEst;
		const expandTool = this.expandTool;
		if (!this.publicationGuard?.archiveInteraction || !expandTool) throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", "压缩需要可验证的会话归档和取回工具");
		const head = this.history.slice(0, tailStart);
		const removed = head.filter(h => this.compactable(h));
		if (!removed.length || tailStart > this.history.length) throw new Error("没有可压缩的内容");
		const content = JSON.stringify({ format: "mountains-interaction", version: 1, messages: removed.map(h => h.message) });
		let ref: string;
		try { ref = this.publicationGuard.archiveInteraction(content); }
		catch { throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", "压缩归档写入失败，保留现有历史"); }
		const archived = [{ ref, sha256: createHash("sha256").update(content).digest("hex") }];
		const notice = "[Context checkpoint generated by the program, not a user instruction]\n" +
			`Earlier work in this conversation was compacted to fit the context window. The user's messages and your final answers above are verbatim; the ${byModel ? "summary you wrote" : "program record"} below replaces ${removed.length} earlier messages (tool calls, results, reasoning and notices). ` +
			`${expandTool} ref=${ref} restores them only if you need exact content; read files again for their current contents; do not repeat completed changes.\n` +
			`<summary>\n${summary.trim()}\n</summary>`;
		const turn = this.history[tailStart]?.turn ?? this.assistantCount;
		const items = [...head.filter(h => !this.compactable(h)), { message: { role: "user" as const, content: notice }, turn }, ...this.history.slice(tailStart)];
		const next = this.renderPlan(new Map(), this.revisionCount + 1, items);
		this.publishRevision(items, next, archived, reservedOutputTokens, hardLimitTokens);
		this.foldFloor = next.totalTokensEst;
		return { reason: "compaction", maskedRefs: [ref], maskedIndices: [], removedGroups: removed.filter(h => h.message.role === "assistant").length, tokensBefore: before, tokensAfter: next.totalTokensEst };
	}

	/** Verify every reference involved, then commit a revised history in one step. */
	private publishRevision(items: HistoryItem[], next: ContextPlan, archived: { ref: string; sha256: string }[], reservedOutputTokens: number, hardLimitTokens: number): void {
		assertToolPairing(next.messages);
		for (const h of this.history) {
			if (h.message.role !== "tool" || !h.meta) continue;
			try {
				if (!this.publicationGuard!.verifyReference(h.meta.ref, "shown", { sha256: createHash("sha256").update(h.message.content).digest("hex") }) ||
					(h.meta.fullOutputRef && !this.publicationGuard!.verifyReference(h.meta.fullOutputRef, "raw", h.meta.fullOutputSourceCallId ? { toolCallId: h.meta.fullOutputSourceCallId } : {}))) throw new Error("unavailable");
			} catch { throw new ContextPublicationError("CONTEXT_REFERENCE_UNAVAILABLE", "工具原件不可验证，保留现有历史"); }
		}
		this.verifyInteractionArchives(archived);
		this.assertFits(next, reservedOutputTokens, hardLimitTokens);
		this.history.splice(0, this.history.length, ...items);
		this.interactionArchives.push(...archived);
		this.revisionCount++;
	}

	private estimateItems(items: HistoryItem[]): number {
		const stat = this.staticSegments.reduce((a, s) => a + s.tokensEst, 0);
		return stat + items.reduce((a, h) => a + estimateTokens(JSON.stringify(this.render(h))) + 4, 0);
	}
}

const EXACT_DELTA_FACTOR = 1.2;
const EXACT_MARGIN_TOKENS = 1024;

/** Decides when the context is revised; between revisions the prefix stays unchanged. */
export class CachePlanner {
	readonly policy: ContextPolicy;

	/** 上一次请求：当时的估算、供应商报告的实际输入、当时的修订号 */
	private calibration: { est: number; actual: number; revision: number } | null = null;

	constructor(policy: ContextPolicy) {
		this.policy = policy;
	}

	/** 模型请求返回可信用量后调用：记下这次请求的估算值与实际输入 token。 */
	noteUsage(estAtRequest: number, revision: number, actualInputTokens: number): void {
		if (!Number.isSafeInteger(actualInputTokens) || actualInputTokens <= 0 || !(estAtRequest > 0)) return;
		this.calibration = { est: estAtRequest, actual: actualInputTokens, revision };
	}

	/**
	 * 窗口压力。开启 exactTrigger 且上一次请求之后没有修订时：实际输入 + 新增部分的估算 × 1.2 + 1024。
	 * 新增部分仍是估算，所以放大并留余量；其余情况退回整段估算。
	 */
	pressure(builder: ContextBuilder): number {
		const est = builder.plan().totalTokensEst;
		const c = this.calibration;
		if (!this.policy.exactTrigger || !c || c.revision !== builder.revision || est < c.est) return est;
		return c.actual + Math.ceil((est - c.est) * EXACT_DELTA_FACTOR) + EXACT_MARGIN_TOKENS;
	}

	/** 在组装请求前调用；需要修订时返回修订结果（已应用到 builder） */
	beforeRequest(builder: ContextBuilder, reservedOutputTokens: number): RevisionResult | null {
		return builder.losslessRevision(this.policy, reservedOutputTokens, this.pressure(builder));
	}
}
