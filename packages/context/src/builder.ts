export type SegmentKind = "system" | "tools" | "history" | "file_content" | "tool_output" | "masked_placeholder" | "overhead";

export interface Segment {
	kind: SegmentKind;
	/** 在 messages 中的下标（历史类段） */
	index?: number;
	tokensEst: number;
	hash: string;
	masked?: boolean;
}

/**
 * Context lines, in estimated tokens. When windowFractions is set and the model window is known, the
 * engine replaces the absolute values with those fractions of the window.
 */
export interface ContextPolicy {
	/** From here, results the program judges lossless fold in the background. */
	triggerTokens: number;
	/** A request whose input plus reserved output exceeds this is refused. */
	hardLimitTokens: number;
	/** From here, the model summarizes the earlier interactions. */
	compactTokens: number;
	/** The newest interactions kept verbatim through a compaction. */
	compactTailTokens: number;
	/** A fold must free at least this much, so the cached prefix changes rarely. */
	minBatchTokens: number;
	/** Interactions before the last N user requests count as settled (default 2). */
	settledUserTurns?: number;
	/** Measure pressure from the last reported input plus an estimate of what was added since. */
	exactTrigger?: boolean;
	windowFractions?: { trigger: number; hard: number; compact: number; tail: number; batch: number };
}

/** Why the program judged a result safe to fold (lossless policy). */
export type FoldReason = "superseded" | "repeated" | "retried" | "settled";
const FOLD_REASON_TEXT: Record<FoldReason, string> = {
	superseded: "superseded by a later read or edit",
	repeated: "the same call succeeded again later",
	retried: "failed, then succeeded on retry",
	settled: "from an earlier finished request",
};
const FOLD_REASONS = Object.keys(FOLD_REASON_TEXT) as FoldReason[];

/** Short notice for one folded result; deterministic, so a restored snapshot can be checked against it. */
export function foldedPlaceholder(name: string, meta: ToolResultMeta, originalTokens: number, reason: FoldReason, expandTool: string): string {
	return `[Folded ${name} result: ${meta.target} (~${originalTokens} tokens; ${FOLD_REASON_TEXT[reason]}). ${expandTool} ref=${meta.ref} restores the text shown then${meta.kind === "file_content" ? "; read the file again for its current contents" : ""}.]`;
}

const ARCHIVE_REF = /^\[Context checkpoint generated by the program, not a user instruction\]\n[\s\S]*? ref=(blob_v2_[0-9a-f]{64}_[0-9a-f]{32}_raw_[0-9a-f]{64})(?: for the complete interaction;| restores)/;
/** Interaction archive named by a program checkpoint notice (fold or compaction), or null. */
export function checkpointArchiveRef(content: string): string | null {
	return ARCHIVE_REF.exec(content)?.[1] ?? null;
}

export interface ToolResultMeta {
	/** file_content：读文件的结果；tool_output：其他工具输出 */
	kind: "file_content" | "tool_output";
	/** 当时发送给模型的完整展示文字（shown）的引用；不一定包含工具原始输出全量。 */
	ref: string;
	/** 完整原始字节的独立引用；ref 始终指当时展示文字，两个视图不能混用偏移。 */
	fullOutputRef?: string;
	/** 原始捕获的调用编号。历史恢复可指向旧调用，不能改填本次恢复调用编号。 */
	fullOutputSourceCallId?: string;
	/** 一句话目标描述，写进占位符 */
	target: string;
	/** 由执行器登记的必要正文；不从不可信工具文字中推断控制指令。 */
	preserve?: "unresolved" | "memory-invalidation" | "error";
	/** Host grants only successful read-only evidence groups permission to checkpoint. */
	checkpointSafe?: boolean;
	/** file_read 实际返回的行范围（来自工具结果，不是请求参数）。没有时不按行范围判断覆盖。 */
	lines?: { start: number; end: number };
}

export interface PublicationGuard {
	/** 存储层验证已落盘、当前会话授权、视图及完整指纹，不重新运行工具。 */
	verifyReference: (ref: string, view: "shown" | "raw", expected: { sha256?: string; toolCallId?: string }) => boolean;
	/** Append-only archive of an entire original interaction; no summarizer or tool rerun. */
	archiveInteraction?: (content: string) => string;
}

export type ContextPublicationErrorCode = "CONTEXT_BUDGET_EXCEEDED" | "CONTEXT_REFERENCE_UNAVAILABLE" | "CONTEXT_TOOL_PAIRING" | "CONTEXT_PROTECTED_CONTENT";

export class ContextPublicationError extends Error {
	readonly code: ContextPublicationErrorCode;
	constructor(code: ContextPublicationErrorCode, message: string) {
		super(message);
		this.name = "ContextPublicationError";
		this.code = code;
	}
}

function freezeTree<T>(value: T): T {
	if (value && typeof value === "object") {
		for (const child of Object.values(value)) freezeTree(child);
		Object.freeze(value);
	}
	return value;
}

/** 验证一组工具调用恰好收到各自一个结果，且结果名称与调用相同。 */
export function assertToolPairing(messages: Message[]): void {
	const seen = new Set<string>();
	const pending = new Map<string, string>();
	for (const message of messages) {
		if (message.role === "tool") {
			if (pending.get(message.toolCallId) !== message.name) throw new ContextPublicationError("CONTEXT_TOOL_PAIRING", `工具结果没有唯一匹配的调用：${message.toolCallId}`);
			pending.delete(message.toolCallId);
			continue;
		}
		if (pending.size) throw new ContextPublicationError("CONTEXT_TOOL_PAIRING", "工具调用的结果尚未齐全，不能发布压缩请求");
		if (message.role !== "assistant") continue;
		for (const call of message.toolCalls) {
			if (!call.id || seen.has(call.id)) throw new ContextPublicationError("CONTEXT_TOOL_PAIRING", `工具调用编号重复或为空：${call.id}`);
			seen.add(call.id);
			pending.set(call.id, call.name);
		}
	}
	if (pending.size) throw new ContextPublicationError("CONTEXT_TOOL_PAIRING", "工具调用的结果尚未齐全，不能发布压缩请求");
}

interface HistoryItem {
	message: Message;
	/** 追加时已有的助手消息条数（用于计算工具结果被模型看过几轮） */
	turn: number;
	meta?: ToolResultMeta;
	/** 遮蔽后固定下来的占位内容（一旦遮蔽，字节永不再变） */
	maskedContent?: string;
}

/** Detached JSON data; this never exposes the builder's live history. */
export interface ContextHistoryItemV1 {
	message: Message;
	turn: number;
	meta?: ToolResultMeta;
	maskedContent?: string;
}

/** Constructor configuration and executable dependencies stay with the caller. */
export interface ContextStateV1 {
	format: "mountains-context";
	version: 1;
	history: ContextHistoryItemV1[];
	revisionCount: number;
	assistantCount: number;
	configHash: string;
	prefixHashes: string[];
}

// Bound validation before allocating copies. These limits concern persisted data,
// not the existing live context or the provider's token window.
const MAX_STATE_ITEMS = 20_000;
const MAX_STATE_CALLS = 1_024;
const MAX_STATE_STRING_BYTES = 8 * 1024 * 1024;
const MAX_STATE_BYTES = 32 * 1024 * 1024;

function stateRecord(value: unknown, keys: readonly string[]): Record<string, unknown> {
	if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("上下文快照对象无效");
	const proto = Object.getPrototypeOf(value);
	if (proto !== Object.prototype && proto !== null) throw new Error("上下文快照必须是纯数据");
	const out: Record<string, unknown> = Object.create(null) as Record<string, unknown>;
	for (const key of Reflect.ownKeys(value)) {
		if (typeof key !== "string" || !keys.includes(key)) throw new Error("上下文快照包含未知字段");
		const field = Object.getOwnPropertyDescriptor(value, key)!;
		if (!field.enumerable || !("value" in field)) throw new Error("上下文快照不能包含访问器");
		out[key] = field.value;
	}
	return out;
}

function stateArray(value: unknown, maximum: number): unknown[] {
	if (!Array.isArray(value) || Object.getPrototypeOf(value) !== Array.prototype || value.length > maximum) throw new Error("上下文快照数组无效或过长");
	const keys = Reflect.ownKeys(value);
	if (keys.length !== value.length + 1) throw new Error("上下文快照数组不能有空位或附加字段");
	for (let index = 0; index < value.length; index++) {
		const field = Object.getOwnPropertyDescriptor(value, String(index));
		if (!field || !field.enumerable || !("value" in field)) throw new Error("上下文快照数组不能包含访问器");
	}
	return value;
}

function stateCounter(value: unknown): number {
	if (typeof value !== "number" || !Number.isSafeInteger(value) || value < 0 || value === Number.MAX_SAFE_INTEGER) throw new Error("上下文快照计数无效");
	return value;
}

// Existing prefix hashes use JSON.stringify's insertion order. Retain it when
// rebuilding validated message/call records rather than silently canonicalizing.
function stateOrdered<T extends object>(source: Record<string, unknown>, validated: T): T {
	const out: Record<string, unknown> = {};
	for (const key of Object.keys(source)) out[key] = (validated as Record<string, unknown>)[key];
	return out as T;
}

/** Validate unknown input without invoking getters, toJSON, or prototype methods. */
/** Characters of a failed result kept visible in its fold notice. */
const FOLDED_FAILURE_CHARS = 400;

/** Program notice that replaced one archived interaction (lossless fold). */
const FOLDED_INTERACTION_NOTICE = /^\[Context checkpoint generated by the program, not a user instruction\]\nFolded \d+ earlier tool calls?[^\n]* ref=blob_v2_[0-9a-f]{64}_[0-9a-f]{32}_raw_[0-9a-f]{64} restores /;

function readContextState(raw: unknown): ContextStateV1 {
	const root = stateRecord(raw, ["format", "version", "history", "revisionCount", "assistantCount", "configHash", "prefixHashes"]);
	if (root.format !== "mountains-context" || root.version !== 1) throw new Error("上下文快照格式或版本无效");
	let stringBytes = 0;
	const string = (value: unknown, maximum = MAX_STATE_STRING_BYTES, nonempty = false): string => {
		if (typeof value !== "string" || value.length > maximum || (nonempty && !value.length)) throw new Error("上下文快照文字无效或过长");
		const size = Buffer.byteLength(value, "utf8");
		stringBytes += size;
		if (size > maximum || stringBytes > MAX_STATE_BYTES) throw new Error("上下文快照超过大小上限");
		return value;
	};
	const revisionCount = stateCounter(root.revisionCount);
	const assistantCount = stateCounter(root.assistantCount);
	const configHash = string(root.configHash, 64);
	if (!/^[a-f0-9]{64}$/.test(configHash)) throw new Error("上下文快照配置指纹无效");
	const history: ContextHistoryItemV1[] = [];
	let previousTurn = 0;
	let lastAssistantTurn: number | null = null;
	for (const rawItem of stateArray(root.history, MAX_STATE_ITEMS)) {
		const item = stateRecord(rawItem, ["message", "turn", "meta", "maskedContent"]);
		const turn = stateCounter(item.turn);
		if (turn < previousTurn || turn > assistantCount) throw new Error("上下文快照历史轮数无效");
		previousTurn = turn;
		const rawMessage = stateRecord(item.message, ["role", "content", "reasoning", "toolCalls", "toolCallId", "name"]);
		const content = string(rawMessage.content);
		let message: Message;
		if (rawMessage.role === "user") {
			stateRecord(item.message, ["role", "content"]);
			// A compaction removes several assistant turns at once, so revised histories only need increasing turns.
			if (lastAssistantTurn !== null ? (revisionCount ? turn <= lastAssistantTurn : turn !== lastAssistantTurn + 1) : !revisionCount && turn !== 0) throw new Error("上下文快照用户轮数无效");
			// A folded interaction's notice stands in for that assistant turn, so the turns after it stay contiguous.
			if (revisionCount && FOLDED_INTERACTION_NOTICE.test(content)) {
				if (turn >= assistantCount) throw new Error("上下文快照收起轮数无效");
				lastAssistantTurn = turn;
			}
			message = stateOrdered(rawMessage, { role: "user" as const, content });
		} else if (rawMessage.role === "assistant") {
			stateRecord(item.message, ["role", "content", "reasoning", "toolCalls"]);
			if (turn >= assistantCount || (lastAssistantTurn !== null && (revisionCount ? turn <= lastAssistantTurn : turn !== lastAssistantTurn + 1))) throw new Error("上下文快照助手轮数无效");
			lastAssistantTurn = turn;
			const toolCalls = stateArray(rawMessage.toolCalls, MAX_STATE_CALLS).map(rawCall => {
				const call = stateRecord(rawCall, ["id", "name", "argumentsJson"]);
				return stateOrdered(call, { id: string(call.id, 4096, true), name: string(call.name, 4096, true), argumentsJson: string(call.argumentsJson) });
			});
			message = stateOrdered(rawMessage, { role: "assistant" as const, content, reasoning: string(rawMessage.reasoning), toolCalls });
		} else if (rawMessage.role === "tool") {
			stateRecord(item.message, ["role", "content", "toolCallId", "name"]);
			if (lastAssistantTurn === null || turn !== lastAssistantTurn + 1) throw new Error("上下文快照工具轮数无效");
			message = stateOrdered(rawMessage, { role: "tool" as const, content, toolCallId: string(rawMessage.toolCallId, 4096, true), name: string(rawMessage.name, 4096, true) });
		} else throw new Error("上下文快照消息角色无效");
		const next: ContextHistoryItemV1 = { message, turn };
		if (message.role === "tool") {
			const meta = stateRecord(item.meta, ["kind", "ref", "fullOutputRef", "fullOutputSourceCallId", "target", "preserve", "lines", "checkpointSafe"]);
			if (meta.kind !== "file_content" && meta.kind !== "tool_output") throw new Error("上下文快照工具元信息无效");
			next.meta = { kind: meta.kind, ref: string(meta.ref, 4096, true), target: string(meta.target) };
			if (Object.hasOwn(meta, "fullOutputRef")) next.meta.fullOutputRef = string(meta.fullOutputRef, 4096, true);
			if (Object.hasOwn(meta, "fullOutputSourceCallId")) {
				if (!next.meta.fullOutputRef) throw new Error("上下文快照原始引用缺失");
				next.meta.fullOutputSourceCallId = string(meta.fullOutputSourceCallId, 4096, true);
			}
			if (Object.hasOwn(meta, "checkpointSafe")) {
				if (typeof meta.checkpointSafe !== "boolean") throw new Error("上下文快照检查点标记无效");
				next.meta.checkpointSafe = meta.checkpointSafe;
			}
			if (Object.hasOwn(meta, "preserve")) {
				if (meta.preserve !== "unresolved" && meta.preserve !== "memory-invalidation" && meta.preserve !== "error") throw new Error("上下文快照保护标记无效");
				next.meta.preserve = meta.preserve;
			}
			if (Object.hasOwn(meta, "lines")) {
				const l = stateRecord(meta.lines, ["start", "end"]);
				if (!Number.isInteger(l.start) || !Number.isInteger(l.end) || (l.start as number) < 1 || (l.end as number) < (l.start as number) - 1) throw new Error("上下文快照行范围无效");
				next.meta.lines = { start: l.start as number, end: l.end as number };
			}
			if (Object.hasOwn(item, "maskedContent")) {
				if (!revisionCount || next.meta.preserve) throw new Error("上下文快照遮蔽状态无效");
				next.maskedContent = string(item.maskedContent);
			}
		} else if (Object.hasOwn(item, "meta") || Object.hasOwn(item, "maskedContent")) throw new Error("上下文快照仅工具消息可含元信息");
		history.push(next);
	}
	if (assistantCount !== (lastAssistantTurn === null ? 0 : lastAssistantTurn + 1) || (revisionCount > 0 && !assistantCount) || (!revisionCount && lastAssistantTurn !== null && assistantCount !== history.filter(item => item.message.role === "assistant").length)) throw new Error("上下文快照助手计数与历史不一致");
	const prefixHashes = stateArray(root.prefixHashes, MAX_STATE_ITEMS + 3).map(value => {
		const hash = string(value, 16);
		if (!/^[a-f0-9]{16}$/.test(hash)) throw new Error("上下文快照前缀指纹无效");
		return hash;
	});
	const state: ContextStateV1 = { format: "mountains-context", version: 1, history, revisionCount, assistantCount, configHash, prefixHashes };
	assertToolPairing(history.map(item => item.message));
	if (Buffer.byteLength(JSON.stringify(state), "utf8") > MAX_STATE_BYTES) throw new Error("上下文快照超过大小上限");
	return state;
}

