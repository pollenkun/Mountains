import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test, type TestContext } from "node:test";
import { AgentSession, BudgetGuard, ScriptedModelAdapter, type EngineOptions, type RecordedResponse } from "../src/index.ts";

function reply(content = "Done.", calls: { id: string; name: string; args: Record<string, unknown> }[] = []): RecordedResponse {
	return { ok: true, message: { role: "assistant", content: calls.length ? "" : content, reasoning: "r",
		toolCalls: calls.map(c => ({ id: c.id, name: c.name, argumentsJson: JSON.stringify(c.args) })) },
		finishReason: calls.length ? "tool_calls" : "stop", responseModel: "deepseek-flash",
		rawUsage: { prompt_tokens: 100, prompt_cache_hit_tokens: 80, prompt_cache_miss_tokens: 20, completion_tokens: 5, total_tokens: 105 },
		httpStatus: 200, error: null, aborted: false };
}
function fixture(t: TestContext) {
	const root = mkdtempSync(join(tmpdir(), "compacted-sessions-"));
	t.after(() => rmSync(root, { recursive: true, force: true }));
	const workspace = join(root, "work"); mkdirSync(workspace);
	const archiveDir = join(root, "archive");
	let n = 0;
	const options = (adapter: ScriptedModelAdapter, extra: Partial<EngineOptions> = {}): EngineOptions => ({
		workspace, dataDir: join(root, `data-${++n}`), sessionId: "ses_compacted", adapter, model: "deepseek-flash", archiveDir, allowSessionSnapshots: true,
		thinking: { enabled: true, effort: "high" }, maxTokens: 1000, checkpoints: false,
		budget: new BudgetGuard({ globalLimit: 100, ledgerPath: join(root, "spend.jsonl") }),
		limits: { maxTurns: 10, maxRequests: 10, maxCost: 10 }, retry: { maxAttempts: 1, baseDelayMs: 0 }, ...extra,
	});
	return { root, workspace, options };
}
const tiny = { triggerTokens: 1, hardLimitTokens: 1_000_000, compactTokens: 1, compactTailTokens: 0, minBatchTokens: 0 };

test("a run that stops after a compaction still leaves a session that exports and restores", async t => {
	const f = fixture(t);
	const adapter = new ScriptedModelAdapter([reply("First answer."), reply("## Goal and requests\n- two questions")]);
	const session = new AgentSession(f.options(adapter, { contextPolicy: tiny, limits: { maxTurns: 10, maxRequests: 1, maxCost: 10 } }));
	assert.equal((await session.run("First question")).status, "completed");
	const second = await session.run("Second question");
	assert.equal(second.status, "limit", second.reason);
	const snapshot = JSON.parse(JSON.stringify(session.exportSnapshot()));
	const resumed = new AgentSession(f.options(new ScriptedModelAdapter([reply("## Goal and requests\n- three questions"), reply("Third answer.")]), { contextPolicy: tiny }));
	resumed.restoreSnapshot(snapshot);
	assert.deepEqual(resumed.builder.plan().messages, session.builder.plan().messages);
	const third = await resumed.run("Third question");
	assert.equal(third.status, "completed", third.reason);
	assert.doesNotThrow(() => resumed.exportSnapshot());
});

test("a skill named with /name stays whole when the program writes the compaction record", async t => {
	const f = fixture(t);
	const skills = join(f.root, "skills");
	mkdirSync(join(skills, "changelog"), { recursive: true });
	writeFileSync(join(skills, "changelog", "SKILL.md"), `---\nname: changelog\ndescription: Write a changelog entry.\n---\n${"Use Keep a Changelog headings. ".repeat(30)}SKILL-END\n`);
	const rejectedSummary: RecordedResponse = { ...reply(), ok: false, rawUsage: null, httpStatus: 400, error: { message: "offline summary unavailable", retryable: false } };
	const adapter = new ScriptedModelAdapter([reply("First answer."), rejectedSummary, reply()]);
	const session = new AgentSession(f.options(adapter, { contextPolicy: tiny, skills: { roots: [{ dir: skills, source: "user" }] } }));
	assert.equal((await session.run("First question")).status, "completed");
	assert.equal((await session.run("/changelog for the 2.1 release")).status, "completed");
	const users = adapter.requests[2]!.messages.filter(m => m.role === "user").map(m => m.content);
	const checkpoint = users.find(c => c.startsWith("[Context checkpoint generated by the program"));
	assert.ok(checkpoint, "a compaction happened before the request");
	assert.match(checkpoint!, /First question/);
	assert.ok(users.some(c => c.startsWith("[Skill loaded at the user's request") && c.includes("SKILL-END")), "the skill text reaches the model whole");
	assert.ok(users.includes("/changelog for the 2.1 release"));
});

test("after a compaction, saving and restoring keeps session search in time order", async t => {
	const f = fixture(t);
	const adapter = new ScriptedModelAdapter([reply("Red it is."), reply("## Goal and requests\n- colour"), reply("Blue it is.")]);
	const session = new AgentSession(f.options(adapter, { contextPolicy: tiny }));
	assert.equal((await session.run("Pick red.")).status, "completed");
	assert.equal((await session.run("Actually, pick blue.")).status, "completed");
	assert.ok(adapter.requests[2]!.messages.some(m => m.role === "user" && m.content.includes("<summary>")), "a compaction happened");
	const entries = (s: AgentSession) => (s as unknown as { sessionIndex: { entries: { bytes: Buffer; metadata: { role: string } }[] } }).sessionIndex.entries
		.map(e => `${e.metadata.role}: ${e.bytes.toString("utf8")}`);
	assert.deepEqual(entries(session), ["user: Pick red.", "assistant: Red it is.", "user: Actually, pick blue.", "assistant: Blue it is."]);
	const resumed = new AgentSession(f.options(new ScriptedModelAdapter([]), { contextPolicy: tiny }));
	resumed.restoreSnapshot(JSON.parse(JSON.stringify(session.exportSnapshot())));
	assert.deepEqual(entries(resumed), entries(session));
});

test("after /name, a skill only the user starts can read its bundled files, also in a restored session", async t => {
	const f = fixture(t);
	const skills = join(f.root, "skills");
	mkdirSync(join(skills, "deploy"), { recursive: true });
	writeFileSync(join(skills, "deploy", "SKILL.md"), "---\nname: deploy\ndescription: Deploy the site.\ndisable-model-invocation: true\n---\nFollow checklist.md.\n");
	writeFileSync(join(skills, "deploy", "checklist.md"), "1. Build.");
	const read = { id: "r1", name: "skill", args: { name: "deploy", file: "checklist.md" } };
	const roots = { skills: { roots: [{ dir: skills, source: "project" as const }] } };
	const adapter = new ScriptedModelAdapter([reply("", [read]), reply()]);
	const session = new AgentSession(f.options(adapter, roots));
	assert.equal((await session.run("/deploy the docs")).status, "completed");
	assert.equal(adapter.requests[0]!.tools.at(-1)!.name, "skill", "the tool is there even though no skill is listed");
	const result = (r: number) => adapter.requests[r]!.messages.find(m => m.role === "tool" && m.toolCallId === "r1")?.content;
	assert.equal(result(1), '<skill_file skill="deploy" path="checklist.md">\n1. Build.\n</skill_file>');
	const again = new ScriptedModelAdapter([reply("", [{ ...read, id: "r2" }]), reply()]);
	const resumed = new AgentSession(f.options(again, roots));
	resumed.restoreSnapshot(JSON.parse(JSON.stringify(session.exportSnapshot())));
	assert.equal((await resumed.run("Check the list again.")).status, "completed");
	assert.match(again.requests[1]!.messages.find(m => m.role === "tool" && m.toolCallId === "r2")?.content ?? "", /^<skill_file skill="deploy"/);
});
