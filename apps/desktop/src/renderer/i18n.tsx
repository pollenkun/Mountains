export type CopyKey = keyof typeof zh;
export type Translate = (key: CopyKey, vars?: Record<string, string | number>) => string;

function fill(text: string, vars?: Record<string, string | number>): string {
	if (!vars) return text;
	return text.replace(/\{(\w+)\}/g, (whole, name: string) => vars[name] !== undefined ? String(vars[name]) : whole);
}

const KNOWN: Record<string, CopyKey> = {
	"轻度": "tierMild", "均衡": "tierBalanced", "高": "tierHigh", "超高": "tierXHigh",
	"禁用思考": "thinkingDisabled", "始终思考": "thinkingAlwaysOn", "最低": "lowest",
	"不支持思考": "noThinking", "支持思考": "thinkingSupported", "可调强度": "thinkingAdjustable", "思考": "thinking",
};

/** A label the engine still sends in Chinese. Unknown words stay as they are. */
export function knownLabel(label: string, t: Translate): string {
	const key = KNOWN[label];
	return key ? t(key) : label;
}

const PROVIDER_EN: Record<string, string> = {
	deepseek: "DeepSeek", zhipu: "Zhipu", moonshot: "Moonshot", openai: "OpenAI", gemini: "Google Gemini",
	qwen: "Alibaba Cloud", siliconflow: "SiliconFlow", openrouter: "OpenRouter", xai: "xAI", anthropic: "Anthropic",
	"openai-compatible": "OpenAI-compatible",
};

export function providerLabel(id: string, fallback: string, lang: Lang): string {
	return lang === "en" ? PROVIDER_EN[id] ?? fallback : fallback;
}

const KEY = "mountains.lang";

export function savedLangChoice(): LangChoice {
	try {
		const saved = localStorage.getItem(KEY);
		return saved === "zh" || saved === "en" || saved === "system" ? saved : "system";
	} catch { return "system"; }
}

export function resolveLang(choice: LangChoice): Lang {
	if (choice === "zh" || choice === "en") return choice;
	return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

const LangContext = createContext<{ choice: LangChoice; lang: Lang; t: Translate; setLang: (choice: LangChoice) => void }>({
	choice: "system", lang: "zh", t: (key, vars) => fill(zh[key], vars), setLang: () => {},
});

export function LangProvider({ children }: { children: ReactNode }) {
	const [choice, setChoice] = useState<LangChoice>(savedLangChoice);
	const lang = resolveLang(choice);
	useEffect(() => { document.documentElement.lang = lang === "zh" ? "zh-CN" : "en"; }, [lang]);
	const setLang = (next: LangChoice) => {
		setChoice(next);
		try { localStorage.setItem(KEY, next); } catch { /* this window only */ }
	};
	const t: Translate = (key, vars) => fill((lang === "en" ? en : zh)[key], vars);
	return <LangContext.Provider value={{ choice, lang, t, setLang }}>{children}</LangContext.Provider>;
}

export function useI18n() { return useContext(LangContext); }
